#!/usr/bin/env python3
"""Generate LeanKissat/Core/{OptionsTable,StatsTable}.lean from Kissat's
options.h and statistics.h (default release build: NDEBUG, no LOGGING,
not QUIET, no EMBEDDED, no STATISTICS/METRICS)."""
import re, sys, os
src, out = sys.argv[1], sys.argv[2]

def num(s):
    s = s.strip()
    env = {'INT_MAX': 2**31 - 1, 'RESTARTINT_DEFAULT': 1, 'STABLE_DEFAULT': 1,
           'TARGET_DEFAULT': 1}
    if s in env: return env[s]
    m = re.fullmatch(r'(\d+)\s*<<\s*(\d+)', s)
    if m: return int(m[1]) << int(m[2])
    return int(float(s))

opts = []
text = open(os.path.join(src, 'options.h')).read()
body = text[text.index('#define OPTIONS'):text.index('// clang-format on')]
for m in re.finditer(r'(OPTION|DBGOPT|EMBOPT|LOGOPT|NQTOPT)\s*\((\w+),\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*"([^"]*)"\)', body):
    kind, name, v, lo, hi, desc = m.groups()
    if kind in ('DBGOPT', 'EMBOPT', 'LOGOPT'):
        continue
    opts.append((name, num(v), num(lo), num(hi), desc))

L = []
L.append('-- Generated by scripts/gen_tables.py from kissat/src/options.h. Do not edit.')
L.append('namespace LeanKissat\n')
L.append('/-- Solver options (`options.h`), default release build. -/')
L.append('structure Options where')
for n, v, lo, hi, d in opts:
    L.append(f'  /-- {d} -/\n  {n} : Nat := {v}')
L.append('  deriving Repr, Inhabited\n')
L.append('/-- `(name, default, low, high, description)` for every option. -/')
L.append('def optionTable : Array (String × Nat × Nat × Nat × String) := #[')
L.append(',\n'.join(f'  ("{n}", {v}, {lo}, {hi}, "{d}")' for n, v, lo, hi, d in opts))
L.append(']\n')
L.append('/-- Get option value by name. -/')
L.append('def Options.get? (o : Options) : String → Option Nat')
for n, *_ in opts:
    L.append(f'  | "{n}" => some o.{n}')
L.append('  | _ => none\n')
L.append('/-- Set option value by name (no range check). -/')
L.append('def Options.set? (o : Options) (name : String) (v : Nat) : Option Options :=')
L.append('  match name with')
for n, *_ in opts:
    L.append(f'  | "{n}" => some {{ o with {n} := v }}')
L.append('  | _ => none\n')
L.append('end LeanKissat')
open(os.path.join(out, 'OptionsTable.lean'), 'w').write('\n'.join(L) + '\n')

text = open(os.path.join(src, 'statistics.h')).read()
body = text[text.index('#define METRICS_COUNTERS_AND_STATISTICS'):text.index('// clang-format on')]
stats = []
# UNITS and TYPE are either string literals or `0` (C NULL pointer).
for m in re.finditer(r'(COUNTER|METRIC|STATISTIC)\s*\((\w+),\s*(\d+),\s*(\w+),\s*("[^"]*"|0),\s*("[^"]*"|0)\)', body):
    kind, name, verbose, other, units, typ = m.groups()
    stats.append((kind, name, int(verbose), other, units.strip(), typ))

def unq(s):
    """String literal contents, `''` for C NULL (`0`)."""
    return s[1:-1] if s.startswith('"') else ''

def opt_lit(s):
    """Lean `Option String` literal: `none` for C NULL (`0`)."""
    return f'some {s}' if s.startswith('"') else 'none'
L = []
L.append('-- Generated by scripts/gen_tables.py from kissat/src/statistics.h. Do not edit.')
L.append('namespace LeanKissat\n')
L.append('/-- Statistics counters (`statistics.h`). Only `COUNTER`s exist in the default')
L.append('  build; `METRIC`/`STATISTIC` entries are ignored there (`GET` yields `UINT64_MAX`). -/')
L.append('structure Stats where')
for k, n, *_ in stats:
    if k == 'COUNTER':
        L.append(f'  {n} : UInt64 := 0')
L.append('  /-- `used[stable].glue[0..127]` -/')
L.append('  usedFocused : Array UInt64 := Array.replicate 128 0')
L.append('  usedStable : Array UInt64 := Array.replicate 128 0')
L.append('  deriving Repr, Inhabited\n')
L.append('/-- `(name, kind, verbose, other, units, type)` for every entry. -/')
L.append('def statsTable : Array (String × String × Nat × String × String × String) := #[')
L.append(',\n'.join(f'  ("{n}", "{k}", {v}, "{o}", "{unq(u)}", "{unq(t)}")' for k, n, v, o, u, t in stats))
L.append(']\n')
L.append('/-- A `COUNTER` entry of `statistics.h` with its accessor (printing order).')
L.append('  `units`/`type` are `none` where C has a `0` (NULL) pointer. -/')
L.append('structure CounterEntry where')
L.append('  name : String')
L.append('  verbose : Nat')
L.append('  /-- name of the secondary-value macro in `statistics.c` -/')
L.append('  other : String')
L.append('  units : Option String')
L.append('  type : Option String')
L.append('  get : Stats → UInt64\n')
L.append('/-- All `COUNTER`s in `statistics.h` order (the order `kissat_statistics_print` uses). -/')
L.append('def counterTable : Array CounterEntry := #[')
L.append(',\n'.join(f'  ⟨"{n}", {v}, "{o}", {opt_lit(u)}, {opt_lit(t)}, fun s => s.{n}⟩' for k, n, v, o, u, t in stats if k == 'COUNTER'))
L.append(']\n')
L.append('/-- Counter value by name (`COUNTER`s only). -/')
L.append('def Stats.get? (s : Stats) : String → Option UInt64')
for k, n, *_ in stats:
    if k == 'COUNTER':
        L.append(f'  | "{n}" => some s.{n}')
L.append('  | _ => none\n')
L.append('end LeanKissat')
open(os.path.join(out, 'StatsTable.lean'), 'w').write('\n'.join(L) + '\n')
print(len(opts), 'options;', sum(1 for s in stats if s[0] == 'COUNTER'), 'counters of', len(stats))

# ---------------------------------------------------------------------------
# Counters: packed representation of the COUNTERs used by the solver core
# (a FloatArray holding UInt64 bit patterns; one cheap in-place update per
# INC/ADD instead of rebuilding an 80-field structure).
counters = [n for k, n, *_ in stats if k == 'COUNTER']
L = []
L.append('-- Generated by scripts/gen_tables.py from kissat/src/statistics.h. Do not edit.')
L.append('import LeanKissat.Core.StatsTable\n')
L.append('namespace LeanKissat\n')
L.append('/-- Statistics counters, packed: entry `i` holds the bits of a `UInt64`.')
L.append(f'  Entries `0..{len(counters)-1}` are the COUNTERs, followed by `used[0].glue[0..127]`')
L.append('  (focused) and `used[1].glue[0..127]` (stable). -/')
L.append('structure Counters where')
L.append('  data : FloatArray')
L.append('  deriving Inhabited\n')
L.append('namespace Counters\n')
L.append(f'def numCounters : Nat := {len(counters)}')
L.append(f'def usedBase (stable : Bool) : Nat := {len(counters)} + (if stable then 128 else 0)\n')
L.append(f'def empty : Counters := ⟨FloatArray.mk (Array.replicate {len(counters) + 256} 0.0)⟩\n')
L.append('instance : EmptyCollection Counters := ⟨empty⟩\n')
L.append('@[inline] def get (c : Counters) (i : Nat) : UInt64 := (c.data.get! i).toBits')
L.append('@[inline] def set (c : Counters) (i : Nat) (v : UInt64) : Counters := ⟨c.data.set! i (Float.ofBits v)⟩')
L.append('@[inline] def add (c : Counters) (i : Nat) (v : UInt64) : Counters := c.set i (c.get i + v)')
L.append('@[inline] def sub (c : Counters) (i : Nat) (v : UInt64) : Counters := c.set i (c.get i - v)\n')
for i, n in enumerate(counters):
    L.append(f'@[inline] def idx_{n} : Nat := {i}')
    L.append(f'@[inline] def {n} (c : Counters) : UInt64 := c.get {i}')
L.append('')
L.append('/-- Convert to the `Stats` record used by the frontend. -/')
L.append('def toStats (c : Counters) : Stats :=')
L.append('  { ' + ',\n    '.join(f'{n} := c.get {i}' for i, n in enumerate(counters)) + ',')
L.append(f'    usedFocused := (Array.range 128).map (fun g => c.get ({len(counters)} + g)),')
L.append(f'    usedStable := (Array.range 128).map (fun g => c.get ({len(counters)} + 128 + g)) }}')
L.append('\nend Counters')
L.append('end LeanKissat')
open(os.path.join(out, 'CountersTable.lean'), 'w').write('\n'.join(L) + '\n')
